// Offline training of the tiny learned denoisers of the scorematch1d demo. NOT part of the
// browser bundle. Re-run from the repository root (node only, about two minutes):
//   node_modules/.bin/esbuild demos/src/scorematch1d/train_dsm.ts --bundle --platform=node --log-level=warning | node > demos/src/scorematch1d/dsm_weights.ts
//
// Data: the three 1D Gaussian mixtures of model.ts (synthetic, no external data).
// Model: MLP (x/√(σ² + 2), ln σ) → ε̂, 2 → 32 → 32 → 1, tanh, seed 5 (model.ts newNet).
// Training: denoising score matching, squared error on the added noise ε, σ log-uniform in
// [0.05, 3], batches of 128 drawn from rng(1000 · data seed + step), Adam lr 0.002.
// Snapshots after 200, 2000 and 20000 steps, as float32 base64. The 200-step snapshot is
// re-trained in demos/test/diffusion-test.ts and must agree to float32 precision.
import { DATA_IDS, data1d, newNet, trainDsm, packNet, SNAP_STEPS, LR } from "./model";
import { Adam } from "../lib/nn";

const out: Record<string, string[]> = {};
for (const id of DATA_IDS) {
  const d = data1d(id), net = newNet(), opt = new Adam(net, LR);
  let done = 0;
  out[id] = [];
  for (const s of SNAP_STEPS) {
    const loss = trainDsm(net, opt, d, done, s - done);
    done = s;
    out[id].push(packNet(net));
    console.error(`${id}: ${s} steps, batch loss ${loss.toFixed(4)}`);
  }
}
console.log("// Generated by train_dsm.ts (see the command at its top). Do not edit by hand.");
console.log("// Learned denoisers of the scorematch1d demo: snapshots after " + SNAP_STEPS.join(", ") + " steps, float32 base64.");
console.log("export const DSM_WEIGHTS: Record<string, string[]> = " + JSON.stringify(out, null, 1) + ";");
