# Offline training of the small learned denoisers of the diffusion2d demo (modern deep learning
# day, unit diffusion/). NOT part of the browser bundle.
#
# Re-run from the repository root (Python 3 with torch and numpy; about a minute on a CPU):
#   python3 demos/src/diffusion2d/train_score.py demos/src/diffusion2d/score_weights.ts
# Data: samples of the demo's 2D Gaussian mixtures (the same numbers as dataSet() in
# model.ts: "two", "ring", "rare", "moons"), drawn fresh at every step.
# Network: (x, y, τ, √ā, √(1 − ā)) → ε̂ (2 numbers), 3 hidden layers of 64 tanh units
# (8.8 k weights). Training: denoising loss E‖ε − ε̂(√ā x_0 + √(1 − ā) ε, τ)‖², τ ~ U(0, 1),
# ā from the cosine or the linear schedule (half of each, as in lib/mixture.ts), batch 512,
# Adam lr 2e-3 with cosine decay, seed 1. Two snapshots per data set: after 150 steps
# ("under-trained") and after 6000 steps ("trained"). Int8 export as lib/q8.ts.
import sys, json, base64
import numpy as np
import torch, torch.nn as nn

OUT = sys.argv[1]
torch.manual_seed(1); np.random.seed(1); torch.set_num_threads(4)
SNAP = {"under": 150, "trained": 6000}


def moons():
    m = [[1.2 * np.cos(np.pi * k / 11) - 0.6, 1.2 * np.sin(np.pi * k / 11) - 0.3] for k in range(12)]
    m += [[0.6 - 1.2 * np.cos(np.pi * k / 11), 0.3 - 1.2 * np.sin(np.pi * k / 11)] for k in range(12)]
    return m


DATA = {
    "two": ([1, 1], [[-1.2, 0.6], [1.2, -0.6]], [0.04, 0.04]),
    "ring": ([1] * 8, [[1.6 * np.cos(2 * np.pi * k / 8), 1.6 * np.sin(2 * np.pi * k / 8)] for k in range(8)], [0.012] * 8),
    "rare": ([0.95, 0.05], [[-0.7, -0.2], [1.6, 1.0]], [0.25, 0.008]),
    "moons": ([1] * 24, moons(), [0.006] * 24),
}


def alpha_bar(tau, cosine):
    s = 0.008
    f = lambda t: torch.cos((t + s) / (1 + s) * np.pi / 2) ** 2
    cos_ab = torch.clamp(f(tau) / f(torch.zeros(1)), min=1e-4)
    lin_ab = torch.exp(-(0.1 * tau + 0.5 * (20 - 0.1) * tau ** 2))
    return torch.where(cosine, cos_ab, lin_ab)


def sample(w, mu, v, n, g):
    w = np.array(w, float) / np.sum(w)
    k = g.choice(len(w), n, p=w)
    return torch.tensor(np.array(mu)[k] + np.sqrt(np.array(v)[k])[:, None] * g.standard_normal((n, 2)), dtype=torch.float32)


def q8(W):
    W = W.astype(np.float64)
    s = np.abs(W).max(axis=1) / 127.0
    s[s == 0] = 1.0
    return np.clip(np.round(W / s[:, None]), -127, 127).astype(np.int8), s


def export(net):
    out = []
    for l in [m for m in net if isinstance(m, nn.Linear)]:
        q, s = q8(l.weight.detach().numpy())
        out.append({"q": base64.b64encode(q.tobytes()).decode(), "s": [float(f"{x:.6g}") for x in s],
                    "b": [float(f"{x:.6g}") for x in l.bias.detach().numpy()], "nIn": int(q.shape[1]), "nOut": int(q.shape[0])})
    return {"layers": out}


sets, loss_info = {}, {}
for name, (w, mu, v) in DATA.items():
    torch.manual_seed(1)
    g = np.random.default_rng(1)
    net = nn.Sequential(nn.Linear(5, 64), nn.Tanh(), nn.Linear(64, 64), nn.Tanh(), nn.Linear(64, 64), nn.Tanh(), nn.Linear(64, 2))
    opt = torch.optim.Adam(net.parameters(), lr=2e-3)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, SNAP["trained"])
    sets[name] = {}
    for step in range(1, SNAP["trained"] + 1):
        x0 = sample(w, mu, v, 512, g)
        tau = torch.rand(512, 1)
        ab = alpha_bar(tau, torch.rand(512, 1) < 0.5)
        eps = torch.randn(512, 2)
        xt = ab.sqrt() * x0 + (1 - ab).sqrt() * eps
        pred = net(torch.cat([xt, tau, ab.sqrt(), (1 - ab).sqrt()], 1))
        loss = ((pred - eps) ** 2).sum(1).mean()
        opt.zero_grad(); loss.backward(); opt.step(); sched.step()
        for k, s in SNAP.items():
            if step == s:
                sets[name][k] = export(net)
                loss_info[f"{name} {k}"] = round(loss.item(), 4)
    print(name, loss_info, file=sys.stderr)

with open(OUT, "w") as f:
    f.write("// Generated by train_score.py (see the command at its top). Do not edit by hand.\n")
    f.write("// Small denoisers ε̂(x, τ) for the 2D data sets, int8 weights (base64), one scale per output unit.\n")
    f.write("import type { MlpQ8 } from \"./model\";\n")
    f.write("export const SCORE_NETS: Record<string, Record<\"under\" | \"trained\", MlpQ8>> = " + json.dumps(sets, separators=(",", ":")) + ";\n")
    f.write("/** Training loss (one batch) at each snapshot. */\n")
    f.write("export const SCORE_LOSS: Record<string, number> = " + json.dumps(loss_info) + ";\n")
print("wrote", OUT, file=sys.stderr)
