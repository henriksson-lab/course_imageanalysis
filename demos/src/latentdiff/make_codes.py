# Precompute the latent codes of the latentdiff demo. NOT part of the browser bundle.
#
# Re-run from the repository root (Python 3 with numpy; no torch needed, a few seconds):
#   python3 -I demos/src/latentdiff/make_codes.py demos/src/vaeimages/train_shapes.py \
#       demos/src/vaeimages/shape_weights.ts demos/src/latentdiff/latent_codes.ts demos/src/latentdiff/latent_check.ts
#
# Data: 800 SYNTHETIC cell masks (200 of each kind: round, elongated, dividing, protrusion),
# made with the mask generator of the vaeimages demo (the functions wobble, blob, capsule,
# shape and finish are read from train_shapes.py and executed unchanged; the training loop
# there is not run), numpy default_rng(seed 41).
# Model: the int8 cell-shape VAE of vaeimages (shape_weights.ts), dequantised exactly as
# vaeimages/imagevae.ts does; only its encoder is run here: mean and sd of q(z | mask).
# Output: latent_codes.ts (means, sds, kinds; 4 decimals) and latent_check.ts (10 masks as
# 8-bit images with their codes, for demos/test/diffusion-test.ts, which runs the TS encoder).
import sys, ast, json, base64, re
import numpy as np

SRC, WEIGHTS, OUT, CHECK = sys.argv[1:5]
N_PER_KIND, SEED = 200, 41

# --- the mask generator of train_shapes.py (module constants SS, g, GX, GY and the functions)
tree = ast.parse(open(SRC).read())
keep = []
for node in tree.body:
    if isinstance(node, ast.FunctionDef) and node.name in ("wobble", "blob", "capsule", "shape", "finish"):
        keep.append(node)
    elif isinstance(node, ast.Assign) and any(isinstance(t, (ast.Name, ast.Tuple)) and
                                              ({getattr(t, "id", None)} | {getattr(e, "id", None) for e in getattr(t, "elts", [])}) & {"SS", "g", "GX", "GY"}
                                              for t in node.targets):
        keep.append(node)
ns = {"np": np}
exec(compile(ast.Module(body=keep, type_ignores=[]), SRC, "exec"), ns)

# --- the int8 encoder, dequantised as in imagevae.ts
txt = open(WEIGHTS).read()
m = re.search(r"export const SHAPE_VAE[^=]*=\s*(\{.*?\});\n", txt, re.S)
W = json.loads(m.group(1))


def deq(l):
    q = np.frombuffer(base64.b64decode(l["q"]), dtype=np.int8).astype(np.float64).reshape(l["nOut"], l["nIn"])
    return q * np.array(l["s"])[:, None], np.array(l["b"], dtype=np.float64)


E1, EM, EV = deq(W["e1"]), deq(W["em"]), deq(W["ev"])


def encode(x):
    h = np.maximum(0, x @ E1[0].T + E1[1])
    mu, lv = h @ EM[0].T + EM[1], h @ EV[0].T + EV[1]
    return mu, np.exp(0.5 * lv)


rng = np.random.default_rng(SEED)
kinds = np.repeat(np.arange(4), N_PER_KIND)
rng.shuffle(kinds)
X = np.stack([ns["finish"](ns["shape"](rng, int(k))).ravel() for k in kinds])
mu, sd = encode(X)
r4 = lambda a: [round(float(v), 4) for v in np.ravel(a)]
with open(OUT, "w") as f:
    f.write("// Generated by make_codes.py (see the command at its top). Do not edit by hand.\n")
    f.write("// Encoder means and sds of 800 synthetic cell masks under the cell-shape VAE of vaeimages, and their kind\n")
    f.write("// (0 round, 1 elongated, 2 dividing, 3 protrusion).\n")
    f.write("export const CODE_MU: number[] = " + json.dumps(r4(mu)) + ";\n")
    f.write("export const CODE_SD: number[] = " + json.dumps(r4(sd)) + ";\n")
    f.write("export const CODE_KIND: number[] = " + json.dumps([int(k) for k in kinds]) + ";\n")

# check set: the first 10 masks as 8-bit images, encoded from the 8-bit version
Xq = np.clip(np.round(X[:10] * 255), 0, 255).astype(np.uint8)
mq, sq = encode(Xq.astype(np.float64) / 255)
with open(CHECK, "w") as f:
    f.write("// Generated by make_codes.py. Ten masks (8-bit, base64) and their encoder means and sds, for the test.\n")
    f.write("export const CHECK_MASKS: string[] = " + json.dumps([base64.b64encode(x.tobytes()).decode() for x in Xq]) + ";\n")
    f.write("export const CHECK_MU: number[] = " + json.dumps([float(v) for v in mq.ravel()]) + ";\n")
    f.write("export const CHECK_SD: number[] = " + json.dumps([float(v) for v in sq.ravel()]) + ";\n")
print(f"800 codes: mean |mu| {np.abs(mu).mean():.3f}, mean sd {sd.mean():.3f}; per kind mean mu " +
      "; ".join(f"{k}: {mu[kinds == k].mean(0).round(2)}" for k in range(4)), file=sys.stderr)
