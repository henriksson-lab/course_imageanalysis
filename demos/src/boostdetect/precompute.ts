// Node script: trains the default cascades and the 50-round boosted classifiers of the
// boostdetect demo and writes them to trained.ts, so the cascade and detect tabs open
// instantly. Re-run after changing synth.ts, model.ts, lib/boost.ts or lib/integral.ts:
//   node_modules/.bin/esbuild demos/src/boostdetect/precompute.ts --bundle --platform=node --log-level=warning | node
import { AdaBoost, Stage } from "../lib/boost";
import { makeDataset, Target } from "./synth";
import { makePool, featureMatrix, nextStage } from "./model";
import { DEFAULTS, VARIANTS } from "./defaults";

declare const require: (m: string) => { writeFileSync(p: string, s: string): void };
const fs = require("fs");

const out: Record<string, unknown> = {};
const pool = makePool();
for (const v of VARIANTS) {
  const train = makeDataset(v.target as Target, DEFAULTS.nPos, DEFAULTS.nNeg, v.seed, { glasses: v.noGlasses ? "never" : "random" });
  const { M } = featureMatrix(pool, train);
  const ab = new AdaBoost(M, train.y);
  for (let r = 0; r < DEFAULTS.monoRounds; r++) ab.round();
  const stages: Stage[] = [], info: unknown[] = [];
  for (let k = 0; k < DEFAULTS.nStages; k++) {
    const r = nextStage(v.target as Target, pool, train.patches.slice(0, DEFAULTS.nPos), stages, DEFAULTS.dStage, DEFAULTS.fStage, DEFAULTS.maxStumps, DEFAULTS.nMine, 100 + k);
    if (!r.stage) break;
    stages.push(r.stage);
    info.push({ stumps: r.report!.stumps, d: r.report!.detection, f: r.report!.falsePositive, pass: r.passBefore, neg: r.negatives });
  }
  out[v.id] = { mono: ab.stumps, cascade: stages, info };
  console.log(v.id, stages.map(s => s.stumps.length).join(" "));
}
fs.writeFileSync("demos/src/boostdetect/trained.ts",
  "// Generated by precompute.ts (default settings of defaults.ts). Do not edit by hand.\n" +
  "import { Stage, Stump } from \"../lib/boost\";\n" +
  "export interface Trained { mono: Stump[]; cascade: Stage[]; info: { stumps: number; d: number; f: number; pass: number; neg: number }[] }\n" +
  "export const TRAINED: Record<string, Trained> = " + JSON.stringify(out) + ";\n");
