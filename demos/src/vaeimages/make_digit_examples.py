# Pick a few MNIST test digits as ready-made inputs for the "Digits" tab of the vaeimages demo.
# NOT part of the browser bundle; the MNIST data is NOT stored in this repository.
#
# Re-run from the repository root (Python 3 with numpy):
#   python3 demos/src/vaeimages/make_digit_examples.py MNIST.npz demos/src/vaeimages/digit_examples.ts [TESTDIR]
# MNIST.npz is the Keras copy of MNIST (keys x_test, y_test). With TESTDIR, the whole test set
# is also written there as raw bytes (mnist_test_x.u8, mnist_test_y.u8) for demos/test/vae-check.ts.
#
# Data: MNIST handwritten digits (Y. LeCun, C. Cortes, C. J. C. Burges). The Keras
# documentation states that LeCun and Cortes hold the copyright and that MNIST is available
# under CC BY-SA 3.0. The 20 images exported here (the 101st and 102nd test image of each
# digit, so not among the 1000 scatter points of mnist_weights.ts) are shared under the same licence.
import sys, json, base64
import numpy as np

d = np.load(sys.argv[1])
x, y = d["x_test"], d["y_test"]
ex = []
for c in range(10):
    for i in np.where(y == c)[0][100:102]:
        ex.append({"label": f"a test {c}", "img": base64.b64encode(x[i].astype(np.uint8).tobytes()).decode()})
with open(sys.argv[2], "w") as f:
    f.write("// Generated by make_digit_examples.py (see the command at its top). Do not edit by hand.\n")
    f.write("// 20 MNIST test digits (LeCun, Cortes & Burges; CC BY-SA 3.0 as stated in the Keras documentation),\n")
    f.write("// 28 × 28 grey bytes (0 = no ink), base64.\n")
    f.write("export const DIGIT_EXAMPLES: { label: string; img: string }[] = " + json.dumps(ex, separators=(",", ":")) + ";\n")
if len(sys.argv) > 3:
    x.astype(np.uint8).tofile(f"{sys.argv[3]}/mnist_test_x.u8")
    y.astype(np.uint8).tofile(f"{sys.argv[3]}/mnist_test_y.u8")
print("wrote", sys.argv[2], file=sys.stderr)
